// Keeps every supported agent tool on the same skills and procedure.
//
// - Claude Code reads `.claude/skills/<name>/SKILL.md` and runs them as `/name`.
// - Antigravity reads `.agents/skills/<name>/SKILL.md`; its `/name` commands come from
//   `.agents/workflows/<name>.md`, which this module generates as thin pointers to the skill.
//
// Both skill copies are installed by `npx skills` (see skills-lock.json) and must stay identical.
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";

export const CLAUDE_SKILLS = ".claude/skills";
export const ANTIGRAVITY_SKILLS = ".agents/skills";
export const ANTIGRAVITY_WORKFLOWS = ".agents/workflows";

const MAX_DESCRIPTION = 250;

function listFiles(root: string): string[] {
  if (!existsSync(root)) return [];
  const out: string[] = [];
  const walk = (dir: string): void => {
    for (const entry of readdirSync(dir)) {
      const path = join(dir, entry);
      if (statSync(path).isDirectory()) walk(path);
      else out.push(relative(root, path).replaceAll("\\", "/"));
    }
  };
  walk(root);
  return out.sort();
}

function readNormalized(path: string): string {
  return readFileSync(path, "utf8").replaceAll("\r\n", "\n");
}

export function skillNames(): string[] {
  if (!existsSync(CLAUDE_SKILLS)) return [];
  return readdirSync(CLAUDE_SKILLS)
    .filter((name) => existsSync(join(CLAUDE_SKILLS, name, "SKILL.md")))
    .sort();
}

/** Differences between the two installed skill trees (line endings ignored). */
export function skillTreeDrift(): string[] {
  const a = listFiles(CLAUDE_SKILLS);
  const b = listFiles(ANTIGRAVITY_SKILLS);
  const drift: string[] = [];
  for (const file of new Set([...a, ...b])) {
    const left = join(CLAUDE_SKILLS, file);
    const right = join(ANTIGRAVITY_SKILLS, file);
    if (!existsSync(left)) drift.push(`${right} exists only for Antigravity`);
    else if (!existsSync(right)) drift.push(`${left} exists only for Claude Code`);
    else if (readNormalized(left) !== readNormalized(right)) drift.push(`${file} differs`);
  }
  return drift;
}

function skillDescription(name: string): string {
  const text = readNormalized(join(CLAUDE_SKILLS, name, "SKILL.md"));
  const match = /^description:\s*(.+)$/m.exec(text);
  const raw = (match?.[1] ?? name).trim().replace(/^["']|["']$/g, "");
  return raw.length > MAX_DESCRIPTION ? `${raw.slice(0, MAX_DESCRIPTION - 1)}…` : raw;
}

/** The Antigravity workflow that exposes skill `name` as the `/name` command. */
export function workflowFor(name: string): string {
  const description = skillDescription(name).replaceAll('"', "'");
  return `---
description: "${description}"
---

<!-- Generated by \`pnpm skills:sync\` from ${CLAUDE_SKILLS}/${name}. Do not edit. -->

Read \`${ANTIGRAVITY_SKILLS}/${name}/SKILL.md\` in full and follow it exactly, as the same procedure Claude Code runs for \`/${name}\`. Follow the repo rules in \`AGENTS.md\` throughout.

When the skill says to:

- **call the Skill tool with "X"** (or run \`/X\`): read \`${ANTIGRAVITY_SKILLS}/X/SKILL.md\` and follow it.
- **spin up a subagent or background agent**: start a separate agent from the Agent Manager with that brief when you can; otherwise do the work yourself in a clearly separated step, and never review your own work in place of an independent review.
- **ask the user**: stop and ask in chat; never answer on the Owner's behalf.
`;
}

/** Workflows that are missing or stale. */
export function workflowDrift(): string[] {
  const drift: string[] = [];
  const names = skillNames();
  for (const name of names) {
    const path = join(ANTIGRAVITY_WORKFLOWS, `${name}.md`);
    if (!existsSync(path)) drift.push(`${path} is missing`);
    else if (readNormalized(path) !== workflowFor(name)) drift.push(`${path} is stale`);
  }
  for (const file of listFiles(ANTIGRAVITY_WORKFLOWS)) {
    const name = file.replace(/\.md$/, "");
    if (!names.includes(name)) drift.push(`${ANTIGRAVITY_WORKFLOWS}/${file} has no matching skill`);
  }
  return drift;
}
